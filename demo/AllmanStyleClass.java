/**
 * Class with Allman style (brace on the next line).
 * The extension must find the opening brace on the line after the class declaration.
 */
public class AllmanStyleClass
{
    private String data;

    public AllmanStyleClass(String data)
    {
        this.data = data;
    }

    public String getData()
    {
        return data;
    }
}
