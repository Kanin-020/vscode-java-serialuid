/**
 * Normal class with K&R style (brace on the same line).
 * The extension should insert serialVersionUID right after the opening brace.
 */
public class NormalClass {

    private String name;
    private int value;

    public NormalClass(String name, int value) {
        this.name = name;
        this.value = value;
    }

    public String getName() {
        return name;
    }

    public int getValue() {
        return value;
    }
}
